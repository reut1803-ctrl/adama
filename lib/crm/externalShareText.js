// הטקסט שמועתק מכרטיס "מהמעגל האישי".
//
// על המסך כתוב ליד השם "(מהמעגל האישי - לא במאגר)". זהו סימון פנימי
// למשדכנות בלבד - הוא מסביר למה אין כאן כרטיס מלא. ברגע שמעתיקים את
// הפרטים כדי לשלוח אותם הלאה, הסימון הזה הוא רעש: מי שמקבל/ת את
// ההודעה אינו/ה מכיר/ה את המאגר, וצריך היה למחוק אותו ידנית כל פעם.
//
// לכן הטקסט המועתק נבנה בלי הסימון, וגם עובר ניקוי: אם הסימון כבר
// נדבק לתוך ההערות (למשל כשהודבקה לשם העתקה קודמת) - הוא יוסר גם משם.

// הסימון כפי שהוא מופיע על המסך
export const EXTERNAL_MARKER = "(מהמעגל האישי - לא במאגר)";

// גרסה סלחנית: מקבלת כל סוג מקף וכל כמות רווחים, כדי שגם נוסח ישן
// שנשמר בהערות ינוקה.
const MARKER_PATTERN = /\(\s*מהמעגל האישי\s*[-־–—]?\s*לא במאגר\s*\)/g;

export const stripExternalMarker = (text) =>
  String(text || "")
    .replace(MARKER_PATTERN, "")
    // רווחים שנשארו יתומים אחרי ההסרה, בסוף שורה או לפני נקודה
    .replace(/[ \t]+$/gm, "")
    .trim();

// הטקסט המלא להעתקה: שם, טלפון לבירורים והערות - בלי שום סימון פנימי
export function externalShareText(person) {
  return [
    stripExternalMarker(person?.name),
    person?.phone ? `טלפון לבירורים: ${String(person.phone).trim()}` : null,
    stripExternalMarker(person?.notes) || null,
  ]
    .filter(Boolean)
    .join("\n");
}
